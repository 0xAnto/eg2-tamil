import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
from eg2tamil.itn import itn  # noqa: E402

# Spoken forms as the model writes them (from FLEURS and IISc-MILE outputs), and words that must stay words.
cases = {
    "ஆயிரத்தி தொள்ளாயிரத்தி எழுவத்தாறு வரை": "1976 வரை",
    "ஆயிரத்தி தொள்ளாயிரத்து அறுவத்தி மூன்று இல் அணை": "1963 இல் அணை",
    "நூற்றி ஒன்பது மெய்நிகர்": "109 மெய்நிகர்",
    "முப்பத்த நாலு கூடுதல்": "34 கூடுதல்",
    "நூத்தம்பது முதல் இருநூறு பிரதிகள்": "150 முதல் 200 பிரதிகள்",
    "இருபத்தைந்து பேர்": "25 பேர்",
    "இரண்டாயிரத்து இருபத்து நான்கு": "2024",
    "ஆயிரத்தி தொள்ளாயிரத்து இருவதுகளில் பெரும்பாலான": "1920 களில் பெரும்பாலான",
    "எழுபது கிலோ மீட்டர்": "70 கிலோ மீட்டர்",
    "இரண்டு லட்சத்து ஐம்பதாயிரம்": "250000",
    "பதினொன்னு முப்பத்த ஐந்து": "11 35",
    # stay as words
    "ஆறு முழுவதும்": "ஆறு முழுவதும்",
    "ஒரு மலையின்": "ஒரு மலையின்",
    "இரண்டு மூன்று நாட்கள்": "இரண்டு மூன்று நாட்கள்",
    "ஆறுமுகம் வந்தார்": "ஆறுமுகம் வந்தார்",
    "இருபதாம் நூற்றாண்டு பத்திரிகை": "20 ஆம் நூற்றாண்டு பத்திரிகை",
    "நூறாவது": "100 ஆவது",
}
for src, want in cases.items():
    got = itn(src)
    assert got == want, f"{src!r}: {got!r} != {want!r}"
assert itn("இரண்டு மீன்", min_value=0) == "2 மீன்"
print("ok")
